"""通过 PostgreSQL 自身解析目标 DDL，核对和修复已有表的结构。

目标结构只在可回滚保存点内的临时表中展开，不创建持久 schema，不改动业务数据。
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

from psycopg import sql


@dataclass(frozen=True)
class Column:
    type_name: str
    not_null: bool
    default: str | None
    identity: str
    generated: str


@dataclass
class Contract:
    columns: dict[str, dict[str, Column]]
    constraints: dict[str, list[tuple[str, str, bool]]]
    indexes: dict[str, tuple[str, bool, str, bool]]


def _read(connection: Any, namespace: str, tables: list[str], index_names: list[str]) -> Contract:
    result = Contract({}, {}, {})
    for table, name, type_name, not_null, default, identity, generated in connection.execute(
        """SELECT c.relname,a.attname,format_type(a.atttypid,a.atttypmod),
                  a.attnotnull,pg_get_expr(d.adbin,d.adrelid),a.attidentity,a.attgenerated
           FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
           JOIN pg_namespace n ON n.oid=c.relnamespace
           LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
           WHERE n.oid=%s::regnamespace AND c.relname=ANY(%s)
             AND a.attnum>0 AND NOT a.attisdropped""", (namespace, tables),
    ):
        result.columns.setdefault(table, {})[name] = Column(
            type_name, not_null, default, identity, generated,
        )
    for table, name, definition, validated in connection.execute(
        """SELECT t.relname,c.conname,pg_get_constraintdef(c.oid),c.convalidated
           FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
           JOIN pg_namespace n ON n.oid=t.relnamespace
           WHERE n.oid=%s::regnamespace AND t.relname=ANY(%s)""", (namespace, tables),
    ):
        definition = re.sub(r" NOT VALID$", "", definition)
        result.constraints.setdefault(table, []).append((name, definition, validated))
    for table, name, unique, definition, valid in connection.execute(
        """SELECT t.relname,i.relname,x.indisunique,pg_get_indexdef(i.oid),
                  x.indisvalid AND x.indisready
           FROM pg_index x JOIN pg_class i ON i.oid=x.indexrelid
           JOIN pg_class t ON t.oid=x.indrelid JOIN pg_namespace n ON n.oid=t.relnamespace
           WHERE n.oid=%s::regnamespace AND (t.relname=ANY(%s) OR i.relname=ANY(%s))""",
        (namespace, tables, index_names),
    ):
        # 表和索引名另行比较；USING 后保留方法、字段、排序、表达式和部分索引条件。
        result.indexes[name] = (table, unique, definition.split(" USING ", 1)[1], valid)
    return result


def _expected(connection: Any, tables: list[dict], indexes: list[dict]) -> Contract:
    from unilabos.persistence.sql import postgres_sql

    names = [table["name"] for table in tables]
    # 子事务退出时撤销全部临时对象及 search_path；读取结果保存在 Python 中。
    with connection.transaction(force_rollback=True):
        connection.execute("SET LOCAL search_path TO pg_temp, public")
        for table in tables:
            ddl = re.sub(
                r"^CREATE TABLE (?:IF NOT EXISTS )?", "CREATE TEMP TABLE ",
                postgres_sql(table["sql"]), flags=re.I,
            )
            connection.execute(ddl)
        for index in indexes:
            connection.execute(postgres_sql(index["sql"]))
        namespace = connection.execute(
            "SELECT nspname FROM pg_namespace WHERE oid=pg_my_temp_schema()"
        ).fetchone()[0]
        return _read(connection, namespace, names, [index["name"] for index in indexes])


def _add_missing_column(connection: Any, table: str, column: str, wanted: Column) -> None:
    """按目标 DDL 经 PostgreSQL 解析后的定义补列。

    类型、默认值和自增来自本进程在临时表上展开的结构，不读取外部 SQL。
    生成列没有可单独复用的表达式，缺这类列时拒绝启动。
    """

    if wanted.generated:
        raise RuntimeError(f"PostgreSQL 表 {table} 缺少生成列：{column}")
    parts = [wanted.type_name]
    if wanted.identity == "a":
        parts.append("GENERATED ALWAYS AS IDENTITY")
    elif wanted.identity == "d":
        parts.append("GENERATED BY DEFAULT AS IDENTITY")
    else:
        if wanted.default is not None:
            parts.append(f"DEFAULT {wanted.default}")
        if wanted.not_null:
            parts.append("NOT NULL")
    connection.execute(
        sql.SQL("ALTER TABLE {} ADD COLUMN {} {}").format(
            sql.Identifier("public", table),
            sql.Identifier(column),
            sql.SQL(" ".join(parts)),
        )
    )


def reconcile(
    connection: Any,
    tables: list[dict],
    objects: list[dict],
    *,
    ignore_primary_key_tables: set[str] | frozenset[str] = frozenset(),
) -> None:
    """只补齐缺失定义；已有定义冲突或数据不合约束时拒绝初始化。"""
    indexes = [obj for obj in objects if obj["type"] == "index"]
    expected = _expected(connection, tables, indexes)
    actual = _read(connection, "public", [table["name"] for table in tables], [index["name"] for index in indexes])
    for table in tables:
        name = table["name"]
        target = sql.Identifier("public", name)
        for column, wanted in expected.columns[name].items():
            present = actual.columns.get(name, {}).get(column)
            if present is None:
                _add_missing_column(connection, name, column, wanted)
                continue
            if (present.type_name, present.identity, present.generated) != (
                wanted.type_name, wanted.identity, wanted.generated,
            ):
                raise RuntimeError(f"PostgreSQL 字段 {name}.{column} 类型或自增定义不一致")
            if wanted.not_null and not present.not_null:
                connection.execute(sql.SQL("ALTER TABLE {} ALTER COLUMN {} SET NOT NULL").format(
                    target, sql.Identifier(column),
                ))
            elif present.not_null != wanted.not_null:
                raise RuntimeError(f"PostgreSQL 字段 {name}.{column} 非空定义不一致")
            if present.default != wanted.default:
                if present.default is not None or wanted.default is None:
                    raise RuntimeError(f"PostgreSQL 字段 {name}.{column} 默认值不一致")
                # 表达式由本进程目标 DDL 经服务器解析得到，不来自用户请求。
                connection.execute(sql.SQL("ALTER TABLE {} ALTER COLUMN {} SET DEFAULT {}").format(
                    target, sql.Identifier(column), sql.SQL(wanted.default),
                ))
        present_constraints = actual.constraints.get(name, [])
        expected_constraints = expected.constraints.get(name, [])
        if name in ignore_primary_key_tables:
            # TimescaleDB hypertable 的唯一/主键必须包含时间分区列；设备历史表
            # 的 PostgreSQL 主键因此与 SQLite 目录中的单列主键不同。
            present_constraints = [
                item
                for item in present_constraints
                if not re.match(r"^PRIMARY KEY\b", item[1], re.I)
            ]
            expected_constraints = [
                item
                for item in expected_constraints
                if not re.match(r"^PRIMARY KEY\b", item[1], re.I)
            ]
        expected_definitions = {definition for _, definition, _ in expected_constraints}
        unexpected = [label for label, definition, _ in present_constraints if definition not in expected_definitions]
        if unexpected:
            raise RuntimeError(f"PostgreSQL 表 {name} 约束定义不一致：{', '.join(unexpected)}")
        by_definition = {definition: (label, validated) for label, definition, validated in present_constraints}
        by_name = {label: definition for label, definition, _ in present_constraints}
        for label, definition, _ in expected_constraints:
            match = by_definition.get(definition)
            if match is not None:
                if not match[1]:
                    connection.execute(sql.SQL("ALTER TABLE {} VALIDATE CONSTRAINT {}").format(
                        target, sql.Identifier(match[0]),
                    ))
                continue
            if label in by_name:
                raise RuntimeError(f"PostgreSQL 表 {name} 约束 {label} 定义不一致")
            connection.execute(sql.SQL("ALTER TABLE {} ADD CONSTRAINT {} {}").format(
                target, sql.Identifier(label), sql.SQL(definition),
            ))
    for index in indexes:
        name = index["name"]
        present = actual.indexes.get(name)
        if present is not None and present != expected.indexes[name]:
            raise RuntimeError(f"PostgreSQL 索引 {name} 定义或有效状态不一致")
