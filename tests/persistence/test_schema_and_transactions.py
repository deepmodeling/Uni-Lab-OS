def test_postgres_columns_and_constraints_match_sqlite(database_mode, tmp_path):
    if database_mode != "postgresql":
        pytest.skip("通过 PostgreSQL 目录核对结构")
    from unilabos.persistence.schema import catalog, objects_for_scope

    constructors = {
        "inventory": lambda: InventoryStore(str(tmp_path / "inventory.db")),
        "workflow": lambda: WorkflowStore(
            tmp_path / "workflow.db", persist_workflow_definitions=False
        ),
        "history": WorkflowHistoryStore,
        "device": DeviceStateStore,
        "edge": lambda: EdgeControlStore(str(tmp_path / "edge.db")),
        "authority": lambda: LocalEdgeAuthorityStore(tmp_path / "authority.db"),
    }
    for scope, create in constructors.items():
        store = create()
        try:
            scope_catalog = (
                objects_for_scope("workflow", persist_workflow_definitions=False)
                if scope == "workflow"
                else catalog()[scope]
            )
            for item in scope_catalog:
                if item["type"] != "table":
                    continue
                rows = store.db._connection.execute(
                    "SELECT column_name,data_type,is_nullable FROM information_schema.columns WHERE table_schema='public' AND table_name=%s",
                    (item["name"],),
                ).fetchall()
                columns = {row[0]: row[1:] for row in rows if row[0] != "_ulab_rowid"}
                assert set(columns) == {column["name"] for column in item["columns"]}
                for column in item["columns"]:
                    actual_type, nullable = columns[column["name"]]
                    expected_type = {
                        "INTEGER": "bigint",
                        "REAL": "double precision",
                        "TEXT": "text",
                        "DATETIME": "text",
                    }[column["type"]]
                    assert actual_type == expected_type, (item["name"], column["name"])
                    if column["notnull"] or column["pk"]:
                        assert nullable == "NO"
                foreign_keys = store.db._connection.execute(
                    "SELECT count(*) FROM pg_constraint WHERE conrelid=%s::regclass AND contype='f'",
                    (item["name"],),
                ).fetchone()[0]
                assert foreign_keys == len({fk["id"] for fk in item["foreign_keys"]})
        finally:
            store.close()


