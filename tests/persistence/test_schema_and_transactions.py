def test_postgresql_replaces_legacy_resource_scope_check(database_mode, tmp_path):
    if database_mode != "postgresql":
        pytest.skip("旧 scope 约束替换通过 PostgreSQL 初始化路径核对")
    store = WorkflowStore(tmp_path / "workflow.db", persist_workflow_definitions=False)
    try:
        legacy = store.db._connection.execute(
            """
            SELECT c.conname
              FROM pg_constraint c
              JOIN pg_class t ON t.oid = c.conrelid
             WHERE t.relname = 'execution_lock_lease' AND c.contype = 'c'
               AND pg_get_constraintdef(c.oid) LIKE '%resource%'
            """
        ).fetchall()
        assert legacy
        for (name,) in legacy:
            store.db._connection.execute(
                f'ALTER TABLE execution_lock_lease DROP CONSTRAINT "{name}"'
            )
        store.db._connection.execute(
            "ALTER TABLE execution_lock_lease ADD CONSTRAINT "
            "execution_lock_lease_scope_legacy CHECK "
            "(scope IN ('device', 'material', 'material_site'))"
        )
    finally:
        store.close()
    reopened = WorkflowStore(tmp_path / "workflow.db", persist_workflow_definitions=False)
    try:
        checks = [
            row[0]
            for row in reopened.db._connection.execute(
                """
                SELECT pg_get_constraintdef(c.oid)
                  FROM pg_constraint c
                  JOIN pg_class t ON t.oid = c.conrelid
                 WHERE t.relname = 'execution_lock_lease' AND c.contype = 'c'
                """
            ).fetchall()
        ]
        assert any("resource" in check for check in checks)
        assert not any(
            "material_site" in check and "resource" not in check for check in checks
        )
    finally:
        reopened.close()


