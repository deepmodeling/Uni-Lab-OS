def test_write_error_can_be_caught_without_poisoning_transaction(database_mode):
    store = DeviceStateStore()
    try:
        with store.db.transaction():
            store.db.execute(
                "INSERT INTO device_property_history(id,device_id,property,value,value_type,recorded_at) "
                "VALUES (1,'device','a','1','int',0)"
            )
            with pytest.raises(IntegrityError):
                store.db.execute(
                    "INSERT INTO device_property_history(id,device_id,property,value,value_type,recorded_at) "
                    "VALUES (1,'device','a','2','int',0)"
                )
            store.db.execute(
                "INSERT INTO device_property_history(id,device_id,property,value,value_type,recorded_at) "
                "VALUES (2,'device','b','3','int',0)"
            )
        assert store.latest_for("device")["b"]["value"] == 3
        with pytest.raises(RuntimeError):
            with store.db.transaction():
                store.db.execute(
                    "UPDATE device_property_history SET value='9' WHERE id=2"
                )
                store.db.execute(
                    "INSERT INTO device_property_history(device_id,property,value,value_type,recorded_at) VALUES ('device','b','9','int',1)"
                )
                raise RuntimeError("模拟提交前失败")
        assert store.latest_for("device")["b"]["value"] == 3
        assert [row["value"] for row in store.history("device", "b")] == [3]
    finally:
        store.close()


def test_two_connections_cannot_double_reserve(database_mode, tmp_path):
    path = str(tmp_path / "inventory.db")
    first = InventoryService(InventoryStore(path))
    second = InventoryService(InventoryStore(path))
    try:
        first.inbound_lot("template", 1, lot_id="lot")

        def reserve(pair):
            service, workflow = pair
            try:
                service.reserve_workflow(
                    workflow, {"node": [MaterialRequirement(lot_id="lot", quantity=1)]}
                )
                return True
            except InsufficientStock:
                return False

        with ThreadPoolExecutor(max_workers=2) as executor:
            assert sorted(executor.map(reserve, [(first, "one"), (second, "two")])) == [
                False,
                True,
            ]
        assert first.store.get_lot("lot")["quantity_reserved"] == 1
    finally:
        first.store.close()
        second.store.close()


