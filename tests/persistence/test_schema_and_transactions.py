def test_query_results_keep_sqlite_scalar_and_row_behavior(database_mode):
    import json

    from unilabos.persistence.database import OperationalError

    store = DeviceStateStore()
    try:
        row = store.db.query_one(
            "SELECT SUM(value) AS total, (1 = 1) AS matched "
            "FROM (SELECT CAST(2 AS INTEGER) AS value UNION ALL SELECT 3) AS numbers"
        )
        assert row["TOTAL"] == 5
        assert type(row["total"]) is int
        assert type(row["matched"]) is int
        assert json.loads(json.dumps(dict(row))) == {"total": 5, "matched": 1}
        with pytest.raises(IndexError):
            _ = row["missing"]
        with pytest.raises(OperationalError):
            store.db.execute("SELECT * FROM")
        assert store.db.query_one("SELECT 1")[0] == 1
    finally:
        store.close()


def test_business_savepoint_rolls_back_only_failed_attempt(database_mode):
    store = DeviceStateStore()
    try:
        with store.db.transaction():
            store.db.execute(
                "INSERT INTO device_property_history(id,device_id,property,value,value_type,recorded_at) "
                "VALUES (1,'device','a','1','int',0)"
            )
            store.db.execute("SAVEPOINT business_attempt")
            store.db.execute("UPDATE device_property_history SET value='2' WHERE id=1")
            store.db.execute("ROLLBACK TO SAVEPOINT business_attempt")
            store.db.execute("RELEASE SAVEPOINT business_attempt")
            store.db.execute(
                "INSERT INTO device_property_history(id,device_id,property,value,value_type,recorded_at) "
                "VALUES (2,'device','b','3','int',0)"
            )
        assert store.latest_for("device")["a"]["value"] == 1
        assert store.latest_for("device")["b"]["value"] == 3
    finally:
        store.close()


def test_inventory_upgrade_owns_handoff_registration_columns(database_mode, tmp_path):
    """库存初始化补齐旧交接字段，不能依赖业务 Authority 构造顺序。"""
    path = tmp_path / "handoff-schema.db"
    store = InventoryStore(path)
    with store.transaction() as connection:
        connection.execute("INSERT INTO station_handoff_identity VALUES (1,?)", ('["existing-station"]',))
        for column in ("registration_request_json", "registration_response_json", "registration_last_error"):
            connection.execute(f"ALTER TABLE container_station_binding DROP COLUMN {column}")
    store.close()
    reopened = InventoryStore(path)
    try:
        columns = {row[1] for row in reopened.db.execute("PRAGMA table_info(container_station_binding)")}
        assert {"registration_request_json", "registration_response_json", "registration_last_error"} <= columns
        assert reopened.db.query_one("SELECT identity_json FROM station_handoff_identity WHERE singleton=1")[0] == '["existing-station"]'
        assert reopened.db.query_one("SELECT COUNT(*) FROM station_handoff_recovery_pending")[0] == 0
    finally:
        reopened.close()
