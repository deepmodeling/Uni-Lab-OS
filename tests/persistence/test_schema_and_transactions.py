def test_postgresql_unacked_outbox_check_does_not_query_sqlite_master(
    database_mode, tmp_path, monkeypatch
):
    """旧发件箱还在时，未确认行检查不能去查 SQLite 目录。"""

    if database_mode != "postgresql":
        pytest.skip("发件箱存在性检查通过 PostgreSQL 启动路径核对")
    import psycopg

    from unilabos.config.config import BasicConfig

    with psycopg.connect(BasicConfig.database_url, autocommit=True) as connection:
        connection.execute(
            """
            CREATE TABLE workflow_station_event_outbox (
                station_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_uuid TEXT NOT NULL UNIQUE,
                create_time TEXT NOT NULL,
                update_time TEXT NOT NULL,
                event_type TEXT NOT NULL,
                aggregate_type TEXT NOT NULL,
                aggregate_uuid TEXT NOT NULL,
                source_kind TEXT NOT NULL,
                source_uuid TEXT NOT NULL,
                idempotency_key TEXT NOT NULL UNIQUE,
                payload TEXT NOT NULL,
                delivery_attempts INTEGER NOT NULL DEFAULT 0,
                last_attempt_at TEXT,
                acked_at TEXT
            )
            """
        )
        connection.execute(
            """
            INSERT INTO workflow_station_event_outbox(
                event_uuid, create_time, update_time, event_type, aggregate_type,
                aggregate_uuid, source_kind, source_uuid, idempotency_key, payload
            ) VALUES (
                'evt-open', '2026-01-01', '2026-01-01', 'job.completed',
                'workflow_task', 'task-1', 'dispatch', 'src-1', 'idem-1', '{}'
            )
            """
        )
    hits: list[str] = []
    original_execute = PostgreSQLDatabase.execute
    original_raw_execute = psycopg.Connection.execute

    def spy_execute(self, sql, parameters=()):
        if "sqlite_master" in str(sql).lower():
            hits.append(str(sql))
        return original_execute(self, sql, parameters)

    def spy_raw_execute(self, query, params=None, **kwargs):
        if "sqlite_master" in str(query).lower():
            hits.append(str(query))
        return original_raw_execute(self, query, params, **kwargs)

    monkeypatch.setattr(PostgreSQLDatabase, "execute", spy_execute)
    monkeypatch.setattr(psycopg.Connection, "execute", spy_raw_execute)
    store = WorkflowStore(tmp_path / "workflow.db", persist_workflow_definitions=False)
    try:
        assert hits == []
        assert "workflow_station_event_outbox" in store.db.table_names()
    finally:
        store.close()


